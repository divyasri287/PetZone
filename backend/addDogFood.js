const addDogFood = async () => {
  await connectDB();
  console.log('🐾 Adding Dog Food products with standing package bag images...\n');

  // Remove only existing Dog Food products to avoid duplicates
  const deleteResult = await Product.deleteMany({ category: { $regex: /^dog[ -]?food$/i } });
  console.log(`🗑️  Removed ${deleteResult.deletedCount} existing Dog Food products.\n`);

  const created = await Product.insertMany(dogFoodProducts);
  console.log(`✅ Added ${created.length} Dog Food products:\n`);

  created.forEach((p, idx) => {
    console.log(`   ${idx + 1}. ${p.name} — ₹${p.price} (Image: ${p.image})`);
  });

  console.log(`\n🎉 Total Dog Food products in DB: ${created.length}`);
  process.exit(0);
};

addDogFood().catch((err) => {
  console.error('❌ Error adding Dog Food products:', err);
  process.exit(1);
});
